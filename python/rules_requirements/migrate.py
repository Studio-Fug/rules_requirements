def _group_of(row: CaseRow) -> str:
    """The test module/class a case belongs to: the path up to ``::``."""
    if row.synthetic:
        return ""
    prefix, sep, _ = row.key.path.partition("::")
    return prefix if sep else ""


def worksheet(
    plan: Plan,
    *,
    inputs: Mapping[str, Iterable[str]] | None = None,
    previous: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """The worksheet document (JSON-compatible) for ``plan``.

    ``previous`` (an earlier worksheet) carries its decisions over to the
    cases and groups that are still contested.
    """
    prev_cases = decisions(previous) if previous else {}
    prev_groups = {
        (g.get("target"), g.get("group")): g.get("owner")
        for g in (previous or {}).get("groups", []) or []
        if isinstance(g, dict)
    }
    by_group: dict[tuple[str, str], list[Unit]] = {}
    for unit in plan.contested:
        by_group.setdefault((unit.row.key.target, _group_of(unit.row)), []).append(unit)

    groups = []
    for (target, group), units in sorted(by_group.items(), key=lambda kv: (natural_key(kv[0][0]), kv[0][1])):
        owner = _owner(prev_groups.get((target, group)))
        proposals = {u.proposed for u in units}
        shared = proposals.pop() if len(proposals) == 1 else ""
        counts = sorted(dedupe([i for u in units for i in u.counts_toward]), key=natural_key)
        cases = []
        for u in units:
            entry: dict[str, Any] = {"path": u.row.key.path, "status": u.row.status}
            if u.counts_toward != counts:
                entry["counts_toward"] = u.counts_toward
            if u.ignored:
                entry["ignored_tags"] = list(u.ignored)
            if u.row.file:
                entry["file"] = u.row.file
            if u.proposed and not shared:
                entry["proposed"], entry["reason"] = u.proposed, u.reason
            decided = _owner(prev_cases.get(u.row.key))
            if decided != owner and decided != OPEN:
                entry["owner"] = decided
            cases.append(entry)
        g: dict[str, Any] = {"target": target, "group": group, "counts_toward": counts}
        tags = sorted(dedupe([i for u in units for i in u.tags]), key=natural_key)
        claims = sorted(dedupe([i for u in units for i in u.claims]), key=natural_key)
        if tags:
            g["tags"] = tags
        if claims:
            g["target_claims"] = claims
        if shared:
            g["proposed"], g["reason"] = shared, units[0].reason
        g["owner"] = owner
        g["cases"] = cases
        groups.append(g)

    involved = {g["target"] for g in groups}
    targets = []
    for target in sorted(plan.claimers, key=natural_key):
        owners = plan.claimers[target]
        if len(owners) < 2 and target not in involved:
            continue
        rows = [r for r in plan.rows.values() if r.key.target == target and not r.target_scope]
        keeps: dict[str, int] = {}
        for unit in plan.units:
            if unit.row.key.target == target and not unit.row.target_scope and len(unit.counts_toward) == 1:
                only = unit.counts_toward[0]
                if only in owners:
                    keeps[only] = keeps.get(only, 0) + 1
        t: dict[str, Any] = {
            "target": target,
            "claimed_by": list(owners),
            "shared": len(owners) > 1,
            "cases": len(rows),
            "per_case_output": any(not r.synthetic for r in rows),
        }
        if keeps:
            t["uncontested"] = keeps
        targets.append(t)

    target_scope = [
        {"case": str(u.row.key), "status": u.row.status, "counts_toward": u.counts_toward}
        for u in plan.units
        if u.row.target_scope and len(u.counts_toward) > 1
    ]
    doc: dict[str, Any] = {"schema": SCHEMA}
    if inputs:
        doc["inputs"] = {k: list(v) for k, v in inputs.items()}
    doc["summary"] = {}  # filled below, once the document it counts is complete
    doc["targets"] = targets
    doc["groups"] = groups
    if target_scope:
        doc["target_scope"] = target_scope
    doc["summary"] = summary(doc, units=len(plan.units), attributed=len(plan.attributed))
    return doc


def _owner(value: Any) -> str:
    text = "" if value is None else str(value).strip()
    if text.lower() == NONE:
        return NONE  # "None", "NONE": the keyword, whatever its case
    return text or OPEN


def summary(doc: Mapping[str, Any], **extra: int) -> dict[str, int]:
    decided = decisions(doc)
    out = dict(extra)
    out.update(
        {
            "contested_units": len(decided),
            "shared_targets": sum(1 for t in doc.get("targets", []) if t.get("shared")),
            "decided": sum(1 for v in decided.values() if v != OPEN),
            "open": sum(1 for v in decided.values() if v == OPEN),
        }
    )
    return out


def decisions(doc: Mapping[str, Any] | None) -> dict[CaseKey, str]:
    """Each contested case's effective decision: its own ``owner``, else its group's."""
    out: dict[CaseKey, str] = {}
    for g in (doc or {}).get("groups", []) or []:
        if not isinstance(g, dict):
            continue
        group_owner = _owner(g.get("owner"))
        for c in g.get("cases", []) or []:
            if isinstance(c, dict) and c.get("path") is not None:
                out[CaseKey(str(g.get("target", "")), str(c["path"]))] = _owner(c.get("owner", group_owner))
    return out


def owner_ids(owner: str) -> list[str]:
    """The ids a case decided ``owner`` must end up declaring: ``[owner]``, or none for ``none``."""
    return [] if owner == NONE else [owner]


def case_files(doc: Mapping[str, Any] | None) -> dict[CaseKey, str]:
    """Each contested case's test source (its row's ``file``), where the evidence named one."""
    out: dict[CaseKey, str] = {}
    for g in (doc or {}).get("groups", []) or []:
        if not isinstance(g, dict):
            continue
        for c in g.get("cases", []) or []:
            if isinstance(c, dict) and c.get("path") is not None and isinstance(c.get("file"), str) and c["file"]:
                out[CaseKey(str(g.get("target", "")), str(c["path"]))] = c["file"]
    return out


def model_edits(doc: Mapping[str, Any]) -> list[dict[str, str]]:
    """The ``verified_by`` edits the worksheet's decisions imply, per (target, requirement).

    ``action`` is ``remove`` (no case of the target is left for it), ``keep``
    (it still owns cases there, and no case went to anyone else),
    ``split`` (it keeps some cases while others went elsewhere — a whole-target
    reference cannot express that; it needs case selectors, from v0.3),
    ``open`` (undecided cases remain) or ``no-evidence`` (the evidence given
    has no result of the target, so nothing can be said: never a reason to
    remove the reference).
    """
    decided = decisions(doc)
    out = []
    for t in doc.get("targets", []) or []:
        if not isinstance(t, dict) or "target" not in t:
            continue
        target = t["target"]
        mine = {k: v for k, v in decided.items() if k.target == target}
        for req in t.get("claimed_by", []) or []:
            owns = bool((t.get("uncontested") or {}).get(req)) or any(v == req for v in mine.values())
            elsewhere = any(v not in (req, OPEN) for v in mine.values())
            pending = any(v == OPEN for v in mine.values())
            if not t.get("cases") and not mine:
                action, why = NO_EVIDENCE, f"the evidence given has no result of {target}; re-plan with its testlogs"
            elif pending:
                action, why = "open", "undecided cases remain"
            elif not owns:
                action, why = "remove", f"no case of {target} is left for {req}"
            elif elsewhere:
                action, why = "split", "it keeps some cases while others went elsewhere: needs case selectors (v0.3)"
            else:
                action, why = "keep", f"{req} owns every decided case"
            out.append({"target": target, "requirement": req, "action": action, "reason": why})
    return out


