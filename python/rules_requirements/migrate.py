"""Migrating to one owner per test case: the attribution worksheet.

Today a test case counts toward *every* id it is tagged with and toward every
requirement whose ``verified_by`` names its target — the union. ``rr migrate
plan`` computes that union over a model and its evidence and lists every
evidence unit (one :class:`~rules_requirements.case_keys.CaseKey`) that counts
toward two or more entities, and every target named by two or more
requirements. The result is a worksheet (``.rrplan``, YAML) on which the
owners of those requirements record one decision per case:

* an entity id — the one requirement (user need, mitigation) it verifies;
* ``none`` — it verifies none of them;
* ``?`` — still open (the initial value).

Decisions are made per group (one test module/class of one target) and
overridden per case. ``rr migrate apply --stage tags`` then rewrites the
test sources to match (:mod:`rules_requirements.tag_codemod`);
:func:`model_edits` lists the ``verified_by`` edits the decisions imply.

Nothing here changes a verdict: the worksheet is data for people.
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass, field
from typing import Any, Iterable, Mapping

from rules_requirements import config as cfg
from rules_requirements._vendor import yaml
from rules_requirements.case_keys import CaseKey, CaseRow, index_cases, run_targets
from rules_requirements.ingest import Evidence
from rules_requirements.model import Model
from rules_requirements.util import dedupe, natural_key

SCHEMA = "rules_requirements/attribution-worksheet/v1"
OPEN = "?"
NONE = "none"
NO_EVIDENCE = "no-evidence"  # a model_edits action

# Entities a tag counts toward today (trace.build_matrix); a tag naming a risk
# or test method is misdirected evidence and counts for nothing.
VERIFIABLE_KINDS = (cfg.REQUIREMENT, cfg.USER_NEED, cfg.MITIGATION)

HEADER = """\
# Attribution worksheet — generated by `rr migrate plan`.
#
# Every evidence unit below counts toward two or more entities today (each id
# it is tagged with, plus every requirement whose verified_by names its
# target). A test case verifies at most one requirement: decide its owner.
#
#   owner: PR-11   the one entity this case verifies
#   owner: none    it verifies none of them
#   owner: "?"     still open
#
# A group's owner applies to each of its cases; add `owner:` to a case to
# override it. `proposed` is a heuristic hint, never a decision. Re-running
# `rr migrate plan --merge THIS_FILE` keeps the decisions made so far.
"""


@dataclass
class Unit:
    """One evidence unit and what it counts toward under today's union."""

    row: CaseRow
    tags: tuple[str, ...]  # declared ids naming verifiable entities
    claims: tuple[str, ...]  # requirements whose verified_by names the target
    ignored: tuple[str, ...] = ()  # declared ids that count for nothing
    proposed: str = ""
    reason: str = ""

    @property
    def counts_toward(self) -> list[str]:
        return sorted(dedupe(list(self.tags) + list(self.claims)), key=natural_key)


@dataclass
class Plan:
    """The union-semantics census a worksheet is rendered from."""

    units: list[Unit]
    claimers: dict[str, list[str]]  # target -> requirements naming it in verified_by
    rows: dict[CaseKey, CaseRow] = field(default_factory=dict)

    @property
    def attributed(self) -> list[Unit]:
        return [u for u in self.units if u.counts_toward]

    @property
    def contested(self) -> list[Unit]:
        return [u for u in self.units if len(u.counts_toward) > 1 and not u.row.target_scope]


def verifiable_ids(model: Model) -> set[str]:
    return {eid for kind in VERIFIABLE_KINDS for eid in model.section(kind)}


def census(model: Model, evidence: Evidence) -> Plan:
    """What every evidence unit counts toward under today's semantics."""
    verifiable = verifiable_ids(model)
    claimers: dict[str, list[str]] = {}
    for req in sorted(model.requirements.values(), key=lambda r: natural_key(r.id)):
        for vb in req.verified_by:
            claimers.setdefault(vb.target, [])
            if req.id not in claimers[vb.target]:
                claimers[vb.target].append(req.id)
    rows = index_cases(evidence)
    units = []
    for row in rows.values():
        # A verified_by label matches the label the evidence was filed under,
        # exactly as trace.build_matrix matches it.
        labels = {c.target for c in row.cases if c.target}
        unit = Unit(
            row=row,
            tags=tuple(i for i in row.declared if i in verifiable),
            claims=tuple(dedupe([r for t in sorted(labels) for r in claimers.get(t, [])])),
            ignored=tuple(i for i in row.declared if i not in verifiable),
        )
        unit.proposed, unit.reason = _propose(model, unit)
        units.append(unit)
    return Plan(units=units, claimers=claimers, rows=rows)


def _ancestors(model: Model, req_id: str) -> set[str]:
    seen: set[str] = set()
    todo = [req_id]
    while todo:
        req = model.requirements.get(todo.pop())
        for parent in req.refines if req else ():
            if parent not in seen:
                seen.add(parent)
                todo.append(parent)
    return seen


def _propose(model: Model, unit: Unit) -> tuple[str, str]:
    """A single owner where the model or the evidence determines one, else ("", "")."""
    ids = unit.counts_toward
    if len(ids) < 2:
        return "", ""
    for cand in ids:
        others = [i for i in ids if i != cand]
        if set(others) <= _ancestors(model, cand):
            return cand, f"{cand} refines {', '.join(others)}, whose verdict rolls up from it"
    tagged = [t for t in unit.tags if t in ids]
    if len(tagged) == 1 and set(ids) - set(tagged) <= set(unit.claims):
        others = [i for i in ids if i != tagged[0]]
        return tagged[0], (
            f"the case's own tag is more specific than the whole-target verified_by of {', '.join(others)}"
        )
    return "", ""


